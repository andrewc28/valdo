"""Generate the parts of the user documentation that must match the code.

    python -m valdo.easy.docgen            rewrite docs/easy/CONFIG_REFERENCE.md and the
                                           generated table in docs/easy/TROUBLESHOOTING.md
    python -m valdo.easy.docgen --check    exit 1 if either file is out of date

CONFIG_REFERENCE.md is generated from the valdo.yaml schema (valdo.easy.project.SCHEMA).
The error-hint table in TROUBLESHOOTING.md is generated from valdo.easy.hints.HINTS; the rest
of that page is written by hand. tests/easy/test_docs.py fails when either is stale.
No torch or upstream VALDO module is imported.
"""

import argparse
import os
import sys

BEGIN_HINTS = "<!-- BEGIN GENERATED: hints (python -m valdo.easy.docgen) -->"
END_HINTS = "<!-- END GENERATED: hints -->"

_KIND_TEXT = {
    "path": "path", "pattern": "path or pattern", "str": "text", "int": "whole number",
    "float": "number", "bool": "true / false", "list_int": "list of whole numbers",
    "list_num": "list of numbers", "list_str": "list of text", "reindex": "auto / true / false",
    "when_opt": "\"all\", \"never\" or a number in [0, 1]",
    "twin_law": "twin law in hkl notation, e.g. `-h,-k,l`, or `auto`",
    "program_path": "path (installation folder or its setup script)",
}

_SECTION_TEXT = {
    "data": ("Part 1: your project",
             "Where the data are, which models to use, where results go. Always look at these."),
    "columns": ("Part 2: detected by `valdo init`",
                "Check these; change them only if init got something wrong."),
    "advanced": ("Part 3: advanced",
                 "Pre-filled with the settings validated on the PTP1B screen (upstream `_TEMPLATES` and "
                 "`PTP1B_pipeline/configs`). Change them only if you know why."),
}


def _fmt(value):
    from valdo.easy.project import format_scalar
    text = format_scalar(value)
    return f"`{text}`"


def _allowed(spec):
    parts = []
    if spec.choices:
        parts.append(" / ".join(f"`{c}`" for c in spec.choices))
    else:
        parts.append(_KIND_TEXT.get(spec.kind, spec.kind))
    if spec.minimum is not None or spec.maximum is not None:
        lo = "" if spec.minimum is None else f">= {spec.minimum:g}"
        hi = "" if spec.maximum is None else f"<= {spec.maximum:g}"
        parts.append(", ".join(x for x in (lo, hi) if x))
    if spec.nullable:
        parts.append("or `null`")
    if spec.required:
        parts.append("**required**")
    return "; ".join(parts)


def _cell(text):
    return str(text).replace("|", "\\|").replace("\n", " ")


def config_reference():
    """Markdown text of docs/easy/CONFIG_REFERENCE.md."""
    from valdo.easy.project import iter_fields
    lines = [
        "# valdo.yaml reference",
        "",
        "<!-- Generated by `python -m valdo.easy.docgen` from valdo/easy/project.py. Do not edit by hand. -->",
        "",
        "**For:** anyone editing `valdo.yaml`. **You need first:** a `valdo.yaml` written by `valdo init`",
        "(see [QUICKSTART.md](QUICKSTART.md)).",
        "",
        "`valdo.yaml` is the one project file. `valdo init` writes it with a comment on every line;",
        "this page lists every setting with its default and allowed values.",
        "",
        "How the file is read:",
        "",
        "- Unknown or misspelled keys are errors, with a suggestion (`advanced.train.epoch` -> did you",
        "  mean `advanced.train.epochs`?). A typo never silently falls back to a default.",
        "- Numbers written as text, such as `'1e-3'` (YAML reads `1e-3` without a dot as text), are",
        "  converted, with a note.",
        "- In paths, `~` and `$VARIABLES` are expanded. Relative paths are relative to the folder that",
        "  holds `valdo.yaml`.",
        "- A missing optional key takes the default below. `valdo init` writes every key, so the file",
        "  is the single source of truth.",
        "- Patterns (`models.per_dataset`, `phases.existing`, `validation.bound_models`) are either a",
        "  path containing `{name}` (replaced by each dataset name), a folder, or a quoted glob. Files",
        "  are matched to datasets by name.",
        "- Column \"upstream\" names the field of the upstream stage config (`<workdir>/configs/<stage>.yaml`)",
        "  that the setting fills.",
        "- `programs.phenix` / `programs.ccp4` name a PHENIX or CCP4 installation. That one line is all",
        "  valdo needs: for the refine stage it sources the installation's setup script in a separate",
        "  `bash` and runs the program with that environment, in every command and batch job (see",
        "  [USER_GUIDE.md](USER_GUIDE.md#refinement-programs)).",
        "",
    ]
    previous = None
    for dotted, spec in iter_fields():
        top = dotted.split(".")[0]
        if top in _SECTION_TEXT and top != previous:
            title, text = _SECTION_TEXT[top]
            lines += ["", f"## {title}", "", text, "",
                      "| setting | default | allowed values | meaning | upstream |", "|---|---|---|---|---|"]
        previous = top
        default = "(none)" if spec.required else _fmt(spec.default)
        lines.append(f"| `{dotted}` | {_cell(default)} | {_cell(_allowed(spec))} | {_cell(spec.doc)} | "
                     f"{('`' + spec.upstream + '`') if spec.upstream else ''} |")
    lines += [
        "",
        "## Checks across settings",
        "",
        "Besides types and ranges, loading stops with an error (saying what to change) when:",
        "",
        "- neither `models.apo` nor `models.per_dataset` is given;",
        "- `phases.source` is `existing` without `phases.existing`, or `refine` without `phases.program`;",
        "- `phases.source` is `input_mtz` or `existing` and `phases.columns.phwt` / `phdelwt` are empty;",
        "- `advanced.train.train_fraction` is not strictly between 0 and 1 (upstream training crashes with",
        "  an empty validation set);",
        "- `advanced.train.n_hidden_layers` is not two positive whole numbers;",
        "- `advanced.train.include_errors` is false (upstream preprocess cannot run without sigma(F));",
        "- `advanced.reconstruct.repeats` > 1 with `ml_recon: true` (upstream crashes);",
        "- `advanced.reindex.cc_min_dif` <= 0 (upstream writes no files);",
        "- `advanced.blobs.extrapolate_factors` is empty;",
        "- `phases.twin_law` is set but `phases.source` is not `refine`;",
        "- `advanced.refine.extra_args` asks for twin refinement (`xray_data.twin_law=...` or `twin_law=...`",
        "  for phenix, `--refmac-key twin` for dimple): set the law in `phases.twin_law` instead, also when",
        "  `phases.twin_law` is null (only then does valdo check the refined indexing and read the twin",
        "  fraction the way twinned data need).",
        "",
        "`valdo check` adds checks that need the data (for example: at least one validation dataset",
        "for the chosen `train_fraction`, a warning below about 100 datasets, and whether",
        "`phases.twin_law` is a twin law of the reference dataset's lattice; `auto` is resolved there to",
        "the only law that lattice allows, and refused when it allows none or several).",
        "",
        "## Environment variables",
        "",
        "| variable | effect |",
        "|---|---|",
        "| `VALDO_NCPU` | overrides `compute.ncpu` for `valdo run` and `valdo report` (job scripts set it to the slots granted) |",
        "| `OMP_NUM_THREADS`, `MKL_NUM_THREADS`, `OPENBLAS_NUM_THREADS` | set to `compute.ncpu` by `valdo run` and `valdo report` unless you set them |",
        "| `CUDA_VISIBLE_DEVICES` | `''` hides GPUs: training then runs on the CPU |",
        "",
    ]
    return "\n".join(lines)


def hints_table():
    """Markdown block (between the markers) listing every known error pattern of hints.py."""
    from valdo.easy.hints import HINTS
    lines = [BEGIN_HINTS, "",
             "| id | stages | what went wrong | likely cause | how to fix |", "|---|---|---|---|---|"]
    for h in HINTS:
        stages = ", ".join(h["stages"]) if h["stages"] else "any"
        lines.append(f"| `{h['id']}` | {stages} | {_cell(h['what'])} | {_cell(h['cause'])} | {_cell(h['fix'])} |")
    lines += ["", END_HINTS]
    return "\n".join(lines)


def _docs_dir(root=None):
    root = root or os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    return os.path.join(root, "docs", "easy")


def _replace_block(text, block):
    start, end = text.find(BEGIN_HINTS), text.find(END_HINTS)
    if start < 0 or end < 0:
        raise ValueError("TROUBLESHOOTING.md lacks the generated-block markers")
    return text[:start] + block + text[end + len(END_HINTS):]


def expected_files(root=None):
    """{path: expected text} for the generated documentation files."""
    docs = _docs_dir(root)
    out = {os.path.join(docs, "CONFIG_REFERENCE.md"): config_reference()}
    trouble = os.path.join(docs, "TROUBLESHOOTING.md")
    with open(trouble) as handle:
        out[trouble] = _replace_block(handle.read(), hints_table())
    return out


def main(argv=None):
    parser = argparse.ArgumentParser(prog="python -m valdo.easy.docgen", description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="only report whether the files are up to date")
    parser.add_argument("--root", help="repository root (default: the one this module lives in)")
    args = parser.parse_args(argv)
    stale = []
    for path, text in expected_files(args.root).items():
        current = open(path).read() if os.path.isfile(path) else None
        if current == text:
            continue
        stale.append(path)
        if not args.check:
            with open(path, "w") as handle:
                handle.write(text)
            print(f"wrote {path}")
    if args.check and stale:
        print("out of date: " + ", ".join(stale) + "\nrun: python -m valdo.easy.docgen")
        return 1
    if not stale:
        print("documentation is up to date")
    return 0


if __name__ == "__main__":  # pragma: no cover
    sys.exit(main())
